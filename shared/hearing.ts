// Слух Джарвиса: что из услышанного — ему, что — эхо его же голоса из колонок, что — перебили. Чистые функции:
// их использует окно Джарвиса в браузере, и их проверяют тесты (server/hearing.test.ts) на живых фразах.
//
// Почему это отдельно: раньше Джарвиса приходилось звать по пять раз. Ответ со словами из его же вопроса
// («да, передай в Радиосеть Москва») он принимал за своё эхо; пока думал — не слышал; секунду после своей реплики
// выбрасывал всё; обычный вопрос без имени («а что по МТС Банку?») пропускал; шум принимал за «перебили».

export const lowRu = (t: string) => t.toLowerCase().replace(/ё/g, 'е').trim();
const words = (t: string) => lowRu(t).split(/[^а-яa-z0-9]+/).filter(Boolean);

export const STOP_RE = /(^|[\s,.!?])(стоп|хватит|стой|достаточно|замолчи|помолчи|тихо|прекрати)([\s,.!?]|$)/;
// Пауза — только по явной просьбе про самого Джарвиса. «Пока не надо» — ответ на его вопрос, а не «замолчи».
export const SLEEP_RE = /(^|[\s,.!?])(пауза|не слушай|отдохни|отключись|помолчи пока|выключи микрофон|не мешай)([\s,.!?]|$)/;
export const RESUME_RE = /(продолж|возвращайся|вернись|работаем|просыпайся|проснись|включись|снова в работу)/;
export const ACK_RE = /^(принял|принято|понял|вижу|ясно|ок|окей|хорошо|увидел)[.!]*$/;

/** Имя персонажа в начале или в середине фразы («Джарвис, …», «слушай, Джарвис, …»); падежи — тоже. */
export function wakeRe(names: string[]) {
  const list = [...new Set(names.map(lowRu))].sort((a, b) => b.length - a.length);
  return new RegExp(`(?:^|[\\s,.!?])(${list.join('|')})[а-я]{0,2}[,.!?\\s]*`, 'i');
}
export function afterWake(t: string, re: RegExp) {
  const m = re.exec(lowRu(t));
  return m ? t.trim().slice(m.index + m[0].length).trim() : t.trim();
}

/** Приветствия и связки в начале («привет», «слушай», «так», «а») не мешают узнать команду или вопрос. */
export const coreOf = (low: string) => low.replace(/^((привет|здравствуй|слушай|так|ну|а|и|окей|ок|эй|смотри|давай|скажи-ка|подскажи-ка)[,.!\s]+)+/, '');

// Фраза начинается с просьбы — это Джарвису и без его имени.
const CMD_START_RE =
  /^(покажи|открой|заведи|создай|передай|назначь|подними|понизь|отклони|напиши|сообщи|закрой|верни|переназначь|закрепи|напомни|прочитай|объясни|расскажи|разберись|займись|проверь|посмотри|найди|сделай|отправь|подскажи|помоги|убери|добавь|включи|выключи|переключи|перемотай|сводка|что горит|что важнее|что я упускаю|что с |сколько|кому )/;
export const isCommand = (t: string) => CMD_START_RE.test(coreOf(lowRu(t)));

// Вопрос о работе пункта — тоже ему, даже без имени: вопросительное слово + слово из дела.
const Q_START_RE = /^(что|чего|какие|какой|какая|каких|сколько|кто|где|почему|зачем|когда|как|есть ли|чем|куда|кому)(\s|$)/;
const DOMAIN_RE =
  /(инцидент|горит|горят|критич|наивысш|высок|срок|дедлайн|команд|жалоб|письм|почт|смен|сбо[йия]|авари|дежур|руководит|передат|передал|распредел|очеред|стен|блок|мтс|банк|интернет|связ|kion|кион|тв\b|sms|смс|сервис|регион|москв|питер|упуска|главн|важн|срочн|сигнал|запрос|вопрос)/;
export const isQuestionForMe = (t: string) => {
  const c = coreOf(lowRu(t));
  return Q_START_RE.test(c) && DOMAIN_RE.test(c);
};

// В окне после его вопроса или ответа — коротко или с просьбой (разговор людей между собой — мимо).
const ANSWER_RE =
  /(^|[\s,.!?])(да|нет|ага|угу|давай|давайте|конечно|согласен|подтверждаю|не надо|не нужно|отмена|отмени|заведи|заводи|завести|создай|передай|передавай|отдай|выдай|назначь|возьми|беру|взял|подними|понизь|отклони|напиши|скажи|сообщи|открой|покажи|убери|закрой|верни|переназначь|закрепи|напомни|прочитай|объясни|расскажи|разберись|займись|проверь|посмотри|найди|сделай|отправь|подскажи|помоги|сколько|кому)([\s,.!?]|$)/;
export const looksForMe = (t: string) => words(t).length <= 3 || ANSWER_RE.test(lowRu(t)) || isCommand(t) || isQuestionForMe(t);

/**
 * Эхо — это его же фраза из колонок, распознанная микрофоном: длинный кусок его реплики подряд.
 * Человек, отвечая, повторяет 1–3 слова из вопроса («да, передай в Радиосеть Москва») — это не эхо.
 */
export function isEcho(heard: string, spoken: string) {
  const h = words(heard).filter((w) => w.length > 2);
  if (h.length < 4 || !spoken) return false;
  const s = words(spoken);
  const set = new Set(s);
  const share = h.filter((w) => set.has(w)).length / h.length;
  if (share >= 0.85) return true;
  // четыре слова его фразы подряд — тоже эхо
  const sj = ` ${s.join(' ')} `;
  for (let k = 0; k + 4 <= h.length; k++) if (sj.includes(` ${h.slice(k, k + 4).join(' ')} `)) return true;
  return false;
}

/**
 * Перебили, пока он говорит: «стоп» — замолчать; человек заговорил — замолчать и слушать.
 * От шума и неточного эха не обрывается: нужно хотя бы три новых слова, и их больше половины услышанного.
 */
export function bargeIn(heard: string, spoken: string): 'stop' | 'talk' | null {
  const low = lowRu(heard);
  const sp = lowRu(spoken);
  const m = STOP_RE.exec(low);
  if (m && low.split(/\s+/).length <= 3 && !sp.includes(m[2])) return 'stop';
  const h = words(heard).filter((w) => w.length > 2);
  const set = new Set(words(spoken));
  const fresh = h.filter((w) => !set.has(w));
  if (fresh.length >= 3 && fresh.length / Math.max(1, h.length) >= 0.6) return 'talk';
  // обратился по имени — тоже перебил
  return null;
}

/** Та же просьба ещё раз (пока он думает, человек повторяет — второй раз не выполняем). */
export function sameRequest(a: string, b: string) {
  const x = words(a).filter((w) => w.length > 2);
  const y = new Set(words(b).filter((w) => w.length > 2));
  if (!x.length || !y.size) return lowRu(a) === lowRu(b);
  return x.filter((w) => y.has(w)).length / x.length >= 0.6;
}

/** Решение по законченной фразе вне разговора: ему ли она (без имени — команда или вопрос о деле). */
export function forMeWithoutName(t: string) {
  return isCommand(t) || isQuestionForMe(t);
}

/** Для персонажа женского рода: «Открыл» → «Открыла», «Нашёл» → «Нашла» в журнале его действий. */
const MASC = /(^|[\s«(:—-])(Услышал|Открыл|Посмотрел|Нашёл|Собрал|Передал|Взял|Поручил|Сменил|Ответил|Указал|Написал|Создал|Запустил|Остановил|Подобрал|Перестроил|Придумал|Вывел|Закрыл|Сделал|поменял|убрал|добавил|поставил|вернул|включил|выключил|сделал|открыл)(?=[\s,.!:;»)]|$)/g;
export function inGender(text: string, p: Persona): string {
  if (!p.fem) return text;
  return text.replace(MASC, (_m, pre: string, w: string) => `${pre}${w === 'Нашёл' ? 'Нашла' : `${w}а`}`);
}
export const personaById = (id: string | null | undefined) => PERSONAS.find((p) => p.id === id) ?? PERSONAS[0];
